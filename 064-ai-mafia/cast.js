  /* ---------- падежи имени игрока-человека (эвристика) ---------- */
  function humanForms(raw) {
    const n = (raw || '').trim().replace(/\s+/g, ' ').slice(0, 18) || 'Саша';
    const name = n.charAt(0).toUpperCase() + n.slice(1);
    const last = name.slice(-1).toLowerCase();
    const stem = name.slice(0, -1);
    const hush = /[гкхжчшщц]$/i.test(stem);
    if (last === 'а') return { nom: name, gen: stem + (hush ? 'и' : 'ы'), dat: stem + 'е', acc: stem + 'у', ins: stem + (/[жчшщц]$/i.test(stem) ? 'ей' : 'ой') };
    if (last === 'я') return { nom: name, gen: stem + 'и', dat: stem + (/и$/i.test(stem) ? 'и' : 'е'), acc: stem + 'ю', ins: stem + 'ей' };
    if (last === 'й') return { nom: name, gen: stem + 'я', dat: stem + 'ю', acc: stem + 'я', ins: stem + 'ем' };
    if (last === 'ь') return { nom: name, gen: stem + 'я', dat: stem + 'ю', acc: stem + 'я', ins: stem + 'ем' };
    if (/[бвгджзклмнпрстфхцчшщ]/i.test(last)) return { nom: name, gen: name + 'а', dat: name + 'у', acc: name + 'а', ins: name + (/[жчшщц]$/i.test(name) ? 'ем' : 'ом') };
    return { nom: name, gen: name, dat: name, acc: name, ins: name };
  }

